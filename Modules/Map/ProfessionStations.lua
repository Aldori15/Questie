function ProfessionStations.IsAvailable(station)
    for _, profession in ipairs(station.professions) do
        local known = QuestieProfessions:HasProfessionAndSkillLevel({profession})
        if known then return true end
    end
    return false
end

function ProfessionStations.Show(key, station)
    local title = Questie:Colorize(l10n(key), "white")
    for _, objectId in ipairs(station.objectIds) do
        local body = not station.showObjectId and {} or nil
        QuestieMap:ShowObject(objectId, station.icon, 0.6, title, body, true, key)
    end
end
