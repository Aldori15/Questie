"""Build compact 4-pixel exploration masks from a 3.3.5 client's overlay alpha.

Usage: python tools/generate_exploration_masks.py CLIENT_DATA STORMLIB_DLL
Requires Pillow and a matching-architecture StormLib DLL. Reads stock archives
only, so custom local map artwork is not incorporated into the shared addon.
"""
import ctypes as C
import io
import json
from pathlib import Path
import re
import sys

from PIL import Image

data, dll = map(Path, sys.argv[1:3])
storm = C.WinDLL(str(dll))
handle = C.c_void_p
storm.SFileOpenArchive.argtypes = [C.c_wchar_p, C.c_uint, C.c_uint, C.POINTER(handle)]
storm.SFileOpenArchive.restype = C.c_bool
storm.SFileOpenFileEx.argtypes = [handle, C.c_char_p, C.c_uint, C.POINTER(handle)]
storm.SFileOpenFileEx.restype = C.c_bool
storm.SFileGetFileSize.argtypes = [handle, C.POINTER(C.c_uint)]
storm.SFileGetFileSize.restype = C.c_uint
storm.SFileReadFile.argtypes = [handle, C.c_void_p, C.c_uint, C.POINTER(C.c_uint), C.c_void_p]
storm.SFileReadFile.restype = C.c_bool
storm.SFileCloseFile.argtypes = [handle]
storm.SFileCloseArchive.argtypes = [handle]


def read(archive, name):
    file = handle()
    if not storm.SFileOpenFileEx(archive, name.encode("ascii"), 0, C.byref(file)):
        return None
    try:
        size = storm.SFileGetFileSize(file, None)
        buf = C.create_string_buffer(size)
        count = C.c_uint()
        if not storm.SFileReadFile(file, buf, size, C.byref(count), None) or count.value != size:
            raise RuntimeError("Failed to read " + name)
        return buf.raw
    finally:
        storm.SFileCloseFile(file)


archives = []
masks = {}
try:
    # Newer stock archives override older ones; locale archives contain some maps.
    paths = [data / name for name in ("common.mpq", "common-2.mpq", "expansion.mpq", "lichking.mpq")]
    locales = sorted(p for p in data.iterdir() if p.is_dir() and re.fullmatch(r"[a-zA-Z]{4}", p.name))
    for locale in locales:
        paths += [locale / (prefix + locale.name + ".mpq") for prefix in ("locale-", "expansion-locale-", "lichking-locale-")]
    for suffix in ("", "-2", "-3"):
        paths.append(data / ("patch" + suffix + ".mpq"))
        paths += [p / ("patch-" + p.name + suffix + ".mpq") for p in locales]
    names = {}
    for path in paths:
        if not path.exists():
            continue
        archive = handle()
        if not storm.SFileOpenArchive(str(path), 0, 0x100, C.byref(archive)):
            raise RuntimeError("Cannot open " + str(path))
        archives.append(archive)
        listing = read(archive, "(listfile)")
        if listing is None:
            raise RuntimeError("Missing listfile: " + str(path))
        for name in listing.decode("utf-8", errors="replace").splitlines():
            match = re.fullmatch(r"Interface\\WorldMap\\([^\\]+)\\(.+?)(\d+)\.blp", name, re.I)
            if match and match[1].lower() != match[2].lower():
                names[name.lower()] = name
    for key, name in sorted(names.items()):
        raw = next((blob for a in reversed(archives) if (blob := read(a, name)) is not None), None)
        if raw is None:
            raise RuntimeError("Missing texture " + name)
        alpha = Image.open(io.BytesIO(raw)).convert("RGBA").getchannel("A")
        # Tile coordinates stay on the native 256-pixel grid, including short edge tiles.
        rows = []
        for y in range(64):
            runs = []
            start = None
            for x in range(65):
                opaque = x < 64 and x * 4 + 2 < alpha.width and y * 4 + 2 < alpha.height and alpha.getpixel((x * 4 + 2, y * 4 + 2)) >= 128
                if opaque and start is None:
                    start = x
                elif not opaque and start is not None:
                    runs.append(chr(33 + start) + chr(33 + x - 1))
                    start = None
            rows.append("".join(runs))
        masks[key.removeprefix("interface\\worldmap\\").removesuffix(".blp")] = "~".join(rows) + "~"
finally:
    for archive in archives:
        storm.SFileCloseArchive(archive)

target = Path(__file__).resolve().parents[1] / "Compat" / "ExplorationMasks.lua"
lines = ["-- Generated by tools/generate_exploration_masks.py from stock 3.3.5 overlay alpha.",
         "-- Each ~-terminated row contains inclusive 4-pixel runs, encoded as ASCII 33 + column.",
         "QuestieCompat.ExplorationMasks = {"]
lines += [f"    [{json.dumps(k)}] = {json.dumps(v)}," for k, v in sorted(masks.items())]
lines += ["}", ""]
target.write_text("\n".join(lines), encoding="utf-8")
print(f"Generated {len(masks)} tile masks, {target.stat().st_size:,} bytes")
